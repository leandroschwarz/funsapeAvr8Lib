void showDigit(const uint8_t *value_p)
{
    static uint8_t index_p = 0;

    DISPLAY_CONTROL_OUT |= (0x0F << DISPLAY_CONTROL_FIRST);
    DISPLAY_SEGMENTS_OUT = value_p[index_p];
    DISPLAY_CONTROL_OUT &= ~(1 << (index_p + DISPLAY_CONTROL_FIRST));
    index_p = (index_p == 3) ? 0 : (index_p + 1);
}


