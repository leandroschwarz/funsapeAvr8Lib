int main()
{
    // -------------------------------------------------------------------------
    // Local variables
    // -------------------------------------------------------------------------

    GpioPin buttonInc;
    GpioPin buttonDec;
    GpioBus display;

    uint8_t counter = 0;

    buttonInc.init(&DDRB, PinIndex::P1);
    buttonInc.setMode(PinMode::INPUT_PULLED_UP);
    buttonDec.init(&DDRB, PinIndex::P2);
    buttonDec.setMode(PinMode::INPUT_PULLED_UP);

    display.init(&DDRD, PinIndex::P0, 8);
    display.setMode(PinMode::OUTPUT_PUSH_PULL);

    // -------------------------------------------------------------------------
    // Enables global interrupt handling
    // -------------------------------------------------------------------------

    sei();

    // -------------------------------------------------------------------------
    // Main loop
    // -------------------------------------------------------------------------

    while(1) {
        // ---------------------------------------------------------------------
        // Reads button I
        // ---------------------------------------------------------------------

        if(!buttonInc.read()) {
            counter = (counter == 9) ? 9 : (counter + 1);
            delayMs(10);
            while(!buttonInc.read()) {
                doNothing();
            }
        }

        // ---------------------------------------------------------------------
        // Reads button D
        // ---------------------------------------------------------------------

        if(!buttonDec.read()) {
            counter = (counter == 0) ? 0 : (counter - 1);
            delayMs(10);
            while(!buttonDec.read()) {
                doNothing();
            }
        }

        display.write(convertToSevenSegments(counter));

    }

    return 0;
}

